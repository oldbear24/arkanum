export interface SkyPaths {
  line: string;
  fill: string;
}

/** A background pattern over the whole card. Only what falls into the window gets seen. */
export function skyPaths(pattern: SkyPattern, H: number): SkyPaths {
  const cy = f(H * 0.4);
  switch (pattern) {
    case 'hvezdy': {
      // The same sky on every render, a card must not change by being redrawn.
      let seed = 7;
      const next = () => {
        seed = (seed * 9301 + 49297) % 233280;
        return seed / 233280;
      };
      let fill = '';
      for (let i = 0, count = Math.round(H / 7); i < count; i++) {
        const x = f(next() * 300);
        const y = f(next() * H);
        const size = next();
        fill += size > 0.82 ? S(x, y, 4, 4.4, 1.2) : C(x, y, f(0.5 + size));
      }
      return { line: '', fill };
    }
    case 'paprsky':
      return { line: R(150, cy, 48, 30, 620, 3.75), fill: '' };
    case 'kruhy': {
      let line = '';
      for (let r = 24; r < H; r += 24) line += C(150, cy, r);
      return { line, fill: '' };
    }
    case 'sit': {
      let line = '';
      for (let x = -H; x < 300; x += 24) line += 'M' + x + ' 0L' + (x + H) + ' ' + H + 'M' + (x + H) + ' 0L' + x + ' ' + H;
      return { line, fill: '' };
    }
    case 'vlny': {
      let line = '';
      for (let y = 16; y < H; y += 20) line += W(-10, 310, y, 3, 22);
      return { line, fill: '' };
    }
    case 'zadny':
      return { line: '', fill: '' };
  }
}
