/** A heart standing on its tip at the given centre. */
const heart = (x: number, y: number, s: number) =>
  'M' + x + ' ' + f(y + s * 0.95) +
  'C' + f(x - s * 0.9) + ' ' + f(y + s * 0.35) + ' ' + f(x - s * 1.05) + ' ' + f(y - s * 0.35) + ' ' + f(x - s * 0.55) + ' ' + f(y - s * 0.6) +
  'C' + f(x - s * 0.25) + ' ' + f(y - s * 0.75) + ' ' + f(x - s * 0.05) + ' ' + f(y - s * 0.5) + ' ' + x + ' ' + f(y - s * 0.25) +
  'C' + f(x + s * 0.05) + ' ' + f(y - s * 0.5) + ' ' + f(x + s * 0.25) + ' ' + f(y - s * 0.75) + ' ' + f(x + s * 0.55) + ' ' + f(y - s * 0.6) +
  'C' + f(x + s * 1.05) + ' ' + f(y - s * 0.35) + ' ' + f(x + s * 0.9) + ' ' + f(y + s * 0.35) + ' ' + x + ' ' + f(y + s * 0.95) + 'Z';

/** A leaf from a point in the direction of an angle in degrees. */
const leaf = (x: number, y: number, angle: number, length: number) => {
  const a = (angle * Math.PI) / 180;
  const tipX = x + length * Math.cos(a);
  const tipY = y + length * Math.sin(a);
  const midX = (x + tipX) / 2;
  const midY = (y + tipY) / 2;
  const nx = (-Math.sin(a) * length) / 3.4;
  const ny = (Math.cos(a) * length) / 3.4;
  return 'M' + f(x) + ' ' + f(y) + 'Q' + f(midX + nx) + ' ' + f(midY + ny) + ' ' + f(tipX) + ' ' + f(tipY) + 'Q' + f(midX - nx) + ' ' + f(midY - ny) + ' ' + f(x) + ' ' + f(y) + 'Z';
};

const wreath = (cx: number, cy: number, rx: number, ry: number, count: number) => {
  let d = '';
  for (let i = 0; i < count; i++) {
    const angle = (i * 360) / count;
    const a = (angle * Math.PI) / 180;
    d += leaf(cx + rx * Math.cos(a), cy + ry * Math.sin(a), angle + 62, 17);
  }
  return d;
};

const ringOfStars = (cx: number, cy: number, r: number, count: number, size: number) => {
  let d = '';
  for (let i = 0; i < count; i++) {
    const a = ((22.5 + (i * 360) / count) * Math.PI) / 180;
    d += S(cx + r * Math.cos(a), cy + r * Math.sin(a), 4, size, size * 0.3);
  }
  return d;
};

